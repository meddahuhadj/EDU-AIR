  const DICT = { en, fr, ar, nl };

  let current = "en";

  function detect() {
    try {
      const saved = localStorage.getItem(KEY);
      if (saved && SUPPORTED.includes(saved)) return saved;
    } catch (e) {}
    try {
      const nav = (navigator.language || "en").toLowerCase();
      const base = nav.split("-")[0];
      if (SUPPORTED.includes(base)) return base;
    } catch (e) {}
    return "en";
  }

  function lookup(key, lang) {
    const langDict = DICT[lang] || en;
    if (Object.prototype.hasOwnProperty.call(langDict, key)) return langDict[key];
    if (Object.prototype.hasOwnProperty.call(en, key)) return en[key];
    return key;
  }

  function t(key, lang) {
    return lookup(key, lang || current);
  }

  function setLang(lang) {
    if (!SUPPORTED.includes(lang)) lang = "en";
    if (lang !== current) {
      current = lang;
      try {
        localStorage.setItem(KEY, lang);
      } catch (e) {}
    }
  }

  function isRTL(lang) {
    return !!RTLS[lang || current];
  }

  function apply() {
    const lang = current;
    document.documentElement.lang = lang;
    document.documentElement.dir = isRTL(lang) ? "rtl" : "ltr";
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = lookup(el.getAttribute("data-i18n"), lang);
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      el.innerHTML = lookup(el.getAttribute("data-i18n-html"), lang);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      el.setAttribute("aria-label", lookup(el.getAttribute("data-i18n-aria"), lang));
    });
    const title = lookup("meta.title", lang);
    if (title && document.title) document.title = title;
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc) metaDesc.setAttribute("content", lookup("meta.desc", lang));
    window.dispatchEvent(new CustomEvent("edulangchange", { detail: { lang } }));
  }

  function init() {
    current = detect();
    setLang(current);
    if (document.readyState === "loading") {
      document.addEventListener("DOMContentLoaded", apply, { once: true });
    } else {
      apply();
    }
  }

  window.eduI18n = {
    SUPPORTED,
    NAMES,
    VERSION,
    t,
    init,
    apply,
    setLang,
    isRTL,
    current: () => current,
  };
